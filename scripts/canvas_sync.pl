#!/usr/bin/perl
# Download Ralph's Canvas calendar feed and write canvas.md (upcoming items).
# Usage: perl scripts/canvas_sync.pl [days]   (default 45)
use strict; use warnings;
use Time::Local qw(timegm timelocal);
use POSIX qw(strftime);
use File::Basename qw(dirname);
use Cwd qw(abs_path);

$ENV{TZ} = 'America/Chicago'; POSIX::tzset();
my $root = dirname(dirname(abs_path($0)));
my $days = shift // 45;

open my $uf, '<', "$root/config/canvas_feed_url.txt" or die "missing config/canvas_feed_url.txt\n";
chomp(my $url = <$uf>); close $uf;
my $ics = `/usr/bin/curl -sSL --max-time 60 "$url"`;
die "Could not download Canvas feed\n" if $? or $ics !~ /BEGIN:VCALENDAR/;

$ics =~ s/\r?\n[ \t]//g;               # unfold folded lines
sub unesc { my $v = shift; $v =~ s/\\n/ /g; $v =~ s/\\([,;\\])/$1/g; $v =~ s/^\s+|\s+$//g; $v }

my (@items, $ev);
for my $line (split /\r?\n/, $ics) {
  if ($line eq 'BEGIN:VEVENT') { $ev = {}; next }
  if ($line eq 'END:VEVENT')   { push @items, $ev if $ev && defined $ev->{t}; undef $ev; next }
  next unless $ev && $line =~ /^([^:]+):(.*)$/;
  my ($k, $v) = ($1, $2); (my $name = $k) =~ s/;.*//;
  if ($name eq 'DTSTART') {
    my ($y,$m,$d,$H,$M,$S,$z) = $v =~ /^(\d{4})(\d\d)(\d\d)(?:T(\d\d)(\d\d)(\d\d)(Z?))?/ or next;
    if (!defined $H) { $ev->{t} = timelocal(0,0,0,$d,$m-1,$y); $ev->{allday} = 1 }
    elsif ($z)       { $ev->{t} = timegm($S,$M,$H,$d,$m-1,$y) }
    else             { $ev->{t} = timelocal($S,$M,$H,$d,$m-1,$y) }  # assume Central
  } elsif ($name =~ /^(SUMMARY|URL|UID)$/) { $ev->{lc $name} = unesc($v) }
}

my @now = localtime; my $today = timelocal(0,0,0,@now[3,4,5]);
my $horizon = $today + $days * 86400;
@items = sort { $a->{t} <=> $b->{t} } grep { $_->{t} >= $today && $_->{t} <= $horizon } @items;

my @out = ("# Canvas — next $days days",
  "_Auto-generated by scripts/canvas_sync.pl on " . strftime('%Y-%m-%d %H:%M', localtime) . " CT. Don't edit by hand._", "");
my $cur = '';
for my $e (@items) {
  my $day = strftime('%Y-%m-%d (%a)', localtime $e->{t});
  if ($day ne $cur) { $cur = $day; push @out, "", "## $day" }
  my $t = $e->{allday} ? 'all day' : strftime('%l:%M %p', localtime $e->{t}); $t =~ s/^\s+//;
  my $kind = ($e->{uid} // '') =~ /assignment/ ? 'assignment' : 'event';
  my $link = $e->{url} ? " — [open]($e->{url})" : '';
  push @out, "- $t — " . ($e->{summary} // '(untitled)') . " ($kind)$link";
}
push @out, "Nothing on Canvas in this window." unless @items;
open my $fh, '>', "$root/canvas.md" or die $!; print $fh join("\n", @out), "\n"; close $fh;
print "Wrote canvas.md with ", scalar(@items), " items.\n";
